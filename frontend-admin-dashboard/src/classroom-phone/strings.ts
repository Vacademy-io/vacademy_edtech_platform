export type PhoneLang = 'en' | 'hi';

export const STRINGS: Record<PhoneLang, PhoneStrings> = { en, hi };

/** Replaces {name} placeholders. A missing value leaves the placeholder visible in tests. */
export function fill(template: string, values: Record<string, string | number>): string {
    return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
        key in values ? String(values[key]) : whole
    );
}

export function detectLang(saved: string | null, browser: string | undefined): PhoneLang {
    if (saved === 'en' || saved === 'hi') return saved;
    return (browser ?? '').toLowerCase().startsWith('hi') ? 'hi' : 'en';
}

export const StringsContext = createContext<PhoneStrings>(en);

export const useStrings = (): PhoneStrings => useContext(StringsContext);
