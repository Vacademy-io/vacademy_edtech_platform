package vacademy.io.admin_core_service.features.commerce.accounts.crypto;

import ch.qos.logback.classic.Logger;
import ch.qos.logback.classic.spi.ILoggingEvent;
import ch.qos.logback.core.read.ListAppender;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.slf4j.LoggerFactory;
import org.springframework.http.HttpStatus;
import vacademy.io.common.exceptions.VacademyException;

import java.security.SecureRandom;
import java.util.Base64;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** The commerce field cipher with keys generated by the test. */
class CommerceFieldCipherTest {

    private static final SecureRandom RANDOM = new SecureRandom();
    private static final String VALUE = testPan();
    private static final String AAD = CommerceFieldCipher.aad("inst-1", "sup-1", "pan");

    private ListAppender<ILoggingEvent> logs;
    private Logger logger;

    @BeforeEach
    void captureLogs() {
        logger = (Logger) LoggerFactory.getLogger(CommerceFieldCipher.class);
        logs = new ListAppender<>();
        logs.start();
        logger.addAppender(logs);
    }

    @AfterEach
    void releaseLogs() {
        logger.detachAppender(logs);
    }

    /** A PAN-shaped value made by the test: five letters, four digits, one letter. */
    private static String testPan() {
        StringBuilder out = new StringBuilder();
        for (int i = 0; i < 5; i++) {
            out.append((char) ('A' + RANDOM.nextInt(26)));
        }
        for (int i = 0; i < 4; i++) {
            out.append((char) ('0' + RANDOM.nextInt(10)));
        }
        return out.append((char) ('A' + RANDOM.nextInt(26))).toString();
    }

    private static String base64Key(int bytes) {
        byte[] raw = new byte[bytes];
        RANDOM.nextBytes(raw);
        return Base64.getEncoder().encodeToString(raw);
    }

    private static String key(String id) {
        return id + ":" + base64Key(32);
    }

    private void assertLogsHoldNo(String... secrets) {
        for (ILoggingEvent event : logs.list) {
            for (String secret : secrets) {
                assertFalse(event.getFormattedMessage().contains(secret), "a log line holds key text");
            }
        }
    }

    private static int status(Runnable call) {
        return assertThrows(VacademyException.class, call::run).getStatus().value();
    }

    @Test
    void roundTripWithPrefixAndKeyId() {
        CommerceFieldCipher cipher = new CommerceFieldCipher(key("k1"), "");
        assertTrue(cipher.isConfigured());
        assertEquals("k1", cipher.activeKeyId());
        assertEquals(List.of(), cipher.previousKeyIds());
        String stored = cipher.encrypt(VALUE, AAD);
        assertTrue(stored.startsWith("cfc1:k1:"));
        assertFalse(stored.contains(VALUE));
        assertFalse(stored.substring("cfc1:k1:".length()).contains("="), "base64url without padding");
        assertEquals(VALUE, cipher.decrypt(stored, AAD));
    }

    @Test
    void twoEncryptionsOfOneValueDiffer() {
        CommerceFieldCipher cipher = new CommerceFieldCipher(key("k1"), null);
        String first = cipher.encrypt(VALUE, AAD);
        String second = cipher.encrypt(VALUE, AAD);
        assertNotEquals(first, second);
        assertEquals(cipher.decrypt(first, AAD), cipher.decrypt(second, AAD));
    }

    @Test
    void anotherRecordInstituteOrFieldDoesNotDecrypt() {
        CommerceFieldCipher cipher = new CommerceFieldCipher(key("k1"), "");
        String stored = cipher.encrypt(VALUE, AAD);
        for (String other : new String[]{CommerceFieldCipher.aad("inst-1", "sup-2", "pan"),
                CommerceFieldCipher.aad("inst-2", "sup-1", "pan"), CommerceFieldCipher.aad("inst-1", "sup-1", "upi")}) {
            IllegalStateException e = assertThrows(IllegalStateException.class, () -> cipher.decrypt(stored, other));
            assertEquals("stored value cannot be read", e.getMessage());
        }
    }

    @Test
    void previousKeyDecryptsAndTheActiveKeyEncrypts() {
        String k1 = key("k1");
        CommerceFieldCipher old = new CommerceFieldCipher(k1, "");
        String written = old.encrypt(VALUE, AAD);
        CommerceFieldCipher rotated = new CommerceFieldCipher(key("k2"), k1);
        assertEquals("k2", rotated.activeKeyId());
        assertEquals(List.of("k1"), rotated.previousKeyIds());
        assertEquals(VALUE, rotated.decrypt(written, AAD));
        assertTrue(rotated.encrypt(VALUE, AAD).startsWith("cfc1:k2:"));
    }

    @Test
    void unknownKeyIdIs503() {
        String stored = new CommerceFieldCipher(key("k1"), "").encrypt(VALUE, AAD);
        CommerceFieldCipher other = new CommerceFieldCipher(key("k2"), "");
        VacademyException e = assertThrows(VacademyException.class, () -> other.decrypt(stored, AAD));
        assertEquals(HttpStatus.SERVICE_UNAVAILABLE, e.getStatus());
        assertTrue(e.getMessage().startsWith("ENCRYPTION_NOT_CONFIGURED: "));
        // Not configured at all: the same.
        assertEquals(503, status(() -> new CommerceFieldCipher("", "").decrypt(stored, AAD)));
    }

    @Test
    void tamperedValueIsRefusedWithoutTheValueInTheMessage() {
        CommerceFieldCipher cipher = new CommerceFieldCipher(key("k1"), "");
        String stored = cipher.encrypt(VALUE, AAD);
        String body = stored.substring("cfc1:k1:".length());
        byte[] raw = Base64.getUrlDecoder().decode(body);
        raw[raw.length - 1] ^= 1;
        String tampered = "cfc1:k1:" + Base64.getUrlEncoder().withoutPadding().encodeToString(raw);
        for (String bad : new String[]{tampered, "cfc2:k1:" + body, "k1:" + body, "cfc1:k1:", "cfc1:k1:!!!", VALUE}) {
            IllegalStateException e = assertThrows(IllegalStateException.class, () -> cipher.decrypt(bad, AAD));
            assertEquals("stored value cannot be read", e.getMessage());
        }
    }

    @Test
    void notConfiguredEncryptIs503() {
        for (String empty : new String[]{null, "", "   "}) {
            CommerceFieldCipher cipher = new CommerceFieldCipher(empty, "");
            assertFalse(cipher.isConfigured());
            assertNull(cipher.activeKeyId());
            assertEquals(503, status(() -> cipher.encrypt(VALUE, AAD)));
            assertEquals(503, status(() -> cipher.keyedHash("pan", "inst-1", VALUE)));
            assertFalse(cipher.roundTrip());
        }
        assertTrue(logs.list.stream().anyMatch(e -> e.getLevel() == ch.qos.logback.classic.Level.WARN));
    }

    @Test
    void malformedKeyIsNotConfiguredAndConstructs() {
        String good = base64Key(32);
        String shortKey = base64Key(31);
        String longKey = base64Key(33);
        String[][] cases = {
                {"K1:" + good, ""},                  // capital letter in the id
                {"toolongid:" + good, ""},           // id longer than 8
                {good, ""},                          // no id at all
                {"k1:not base64 at all!", ""},       // bad base64
                {"k1:" + shortKey, ""},              // 31 bytes
                {"k1:" + longKey, ""},               // 33 bytes
                {"k1:" + good, "k1:" + base64Key(32)}, // previous key with the active id
                {"k1:" + good, "k2:" + good + ",k2:" + base64Key(32)}, // duplicate previous id
                {"k1:" + good, "k2:" + shortKey},    // malformed previous key
        };
        for (int i = 0; i < cases.length; i++) {
            String[] c = cases[i];
            String label = "case " + i;
            logs.list.clear();
            CommerceFieldCipher cipher = assertDoesNotThrow(() -> new CommerceFieldCipher(c[0], c[1]));
            assertFalse(cipher.isConfigured(), label);
            assertNull(cipher.activeKeyId());
            assertEquals(List.of(), cipher.previousKeyIds());
            assertEquals(503, status(() -> cipher.encrypt(VALUE, AAD)));
            assertEquals(1, logs.list.stream().filter(e -> e.getLevel() == ch.qos.logback.classic.Level.ERROR).count());
            assertLogsHoldNo(good, shortKey, longKey, "not base64 at all");
            assertFalse(cipher.toString().contains(good));
        }
    }

    @Test
    void keyedHashIsStableAndDiffersByInstituteAndPurpose() {
        String k1 = key("k1");
        CommerceFieldCipher cipher = new CommerceFieldCipher(k1, "");
        String hash = cipher.keyedHash("pan", "inst-1", VALUE);
        assertEquals(64, hash.length());
        assertTrue(hash.matches("^[0-9a-f]{64}$"));
        assertEquals(hash, cipher.keyedHash("pan", "inst-1", VALUE));
        assertEquals(hash, new CommerceFieldCipher(k1, "").keyedHash("pan", "inst-1", VALUE));
        assertNotEquals(hash, cipher.keyedHash("pan", "inst-2", VALUE));
        assertNotEquals(hash, cipher.keyedHash("other", "inst-1", VALUE));
        assertNotEquals(hash, new CommerceFieldCipher(key("k1"), "").keyedHash("pan", "inst-1", VALUE));
    }

    @Test
    void roundTripProbe() {
        assertTrue(new CommerceFieldCipher(key("k1"), "").roundTrip());
        assertFalse(new CommerceFieldCipher("", "").roundTrip());
    }

    @Test
    void toStringHoldsNoKey() {
        String keyText = base64Key(32);
        String previous = base64Key(32);
        CommerceFieldCipher cipher = new CommerceFieldCipher("k1:" + keyText, "k0:" + previous);
        String text = cipher.toString();
        assertFalse(text.contains(keyText));
        assertFalse(text.contains(previous));
        assertTrue(text.contains("configured=true"));
        assertTrue(text.contains("k1"));
        assertTrue(text.contains("k0"));
        assertLogsHoldNo(keyText, previous);
    }
}
