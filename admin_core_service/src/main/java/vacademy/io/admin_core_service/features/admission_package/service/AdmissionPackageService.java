package vacademy.io.admin_core_service.features.admission_package.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.util.StringUtils;
import vacademy.io.admin_core_service.features.admission_package.entity.AdmissionPackage;
import vacademy.io.admin_core_service.features.admission_package.entity.AdmissionPackageCourse;
import vacademy.io.admin_core_service.features.admission_package.repository.AdmissionPackageCourseRepository;
import vacademy.io.admin_core_service.features.admission_package.repository.AdmissionPackageRepository;
import vacademy.io.admin_core_service.features.fee_management.dto.DiscountSpecDTO;
import vacademy.io.admin_core_service.features.fee_management.dto.InstallmentScheduleDTO;
import vacademy.io.admin_core_service.features.fee_management.service.AdmissionPackageSplitter;
import vacademy.io.admin_core_service.features.fee_management.service.InstallmentScheduleService;
import vacademy.io.admin_core_service.features.learner_management.dto.AdmissionPackageDTO;
import vacademy.io.admin_core_service.features.learner_management.dto.AdmissionPackagePreviewDTO;
import vacademy.io.admin_core_service.features.learner_management.dto.AssignmentItemDTO;
import vacademy.io.admin_core_service.features.learner_management.dto.CpoEnrollmentConfigDTO;
import vacademy.io.admin_core_service.features.learner_management.service.DefaultInviteResolver;
import vacademy.io.admin_core_service.features.user_subscription.enums.PaymentOptionType;
import vacademy.io.common.exceptions.VacademyException;

import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Admission packages on the Enroll wizard path (POST /v3/learner-management/assign with
 * {@code admission_package}). {@link #prepare} turns the package into a per-course
 * {@code cpo_config} before any enrollment runs — each course then goes through the existing
 * installment-schedule path unchanged — and {@link #save} records which plans belong together
 * once they exist. The admission receipt is generated by the caller from the payment logs.
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class AdmissionPackageService {

    private static final ObjectMapper MAPPER = new ObjectMapper().findAndRegisterModules();

    private final InstallmentScheduleService installmentScheduleService;
    private final AdmissionPackageRepository admissionPackageRepository;
    private final AdmissionPackageCourseRepository admissionPackageCourseRepository;

    /** The split, ready to be saved per learner and shown in the response. */
    public record Plan(AdmissionPackageDTO request, List<String> packageSessionIds,
                       List<AdmissionPackageSplitter.CourseShare> shares, AdmissionPackagePreviewDTO preview) {
    }

    /**
     * Validates the package, splits it across the courses and writes each course's share into
     * its assignment as a {@code cpo_config} (schedule rows with their discounts, and its part of
     * the payment at admission). Throws with an admin-readable message when the package cannot
     * be split; nothing has been enrolled at that point.
     *
     * @param configs the resolved invite/plan of each assignment, in the same order
     */
    public Plan prepare(List<AssignmentItemDTO> assignments, List<DefaultInviteResolver.ResolvedConfig> configs,
                        AdmissionPackageDTO pkg) {
        if (assignments == null || assignments.size() < 2) {
            throw new VacademyException("Pick at least two courses to enroll as a package");
        }
        Set<String> sessions = new HashSet<>();
        List<BigDecimal> fees = new ArrayList<>();
        for (int i = 0; i < assignments.size(); i++) {
            AssignmentItemDTO a = assignments.get(i);
            if (!sessions.add(a.getPackageSessionId())) {
                throw new VacademyException("The same course appears twice in the package");
            }
            if (a.getCpoConfig() != null || a.getAdminDiscount() != null) {
                throw new VacademyException("Set the discount and schedule on the package, not on a single course");
            }
            fees.add(courseFee(configs.get(i)));
        }

        boolean offline = "OFFLINE".equalsIgnoreCase(pkg.getPaymentMode());
        BigDecimal paid = offline && pkg.getPaymentAmount() != null
                ? BigDecimal.valueOf(pkg.getPaymentAmount()) : BigDecimal.ZERO;
        List<AdmissionPackageSplitter.PackageRow> rows = new ArrayList<>();
        for (InstallmentScheduleDTO.RowDTO r : pkg.getRows() == null ? List.<InstallmentScheduleDTO.RowDTO>of() : pkg.getRows()) {
            rows.add(new AdmissionPackageSplitter.PackageRow(r.getDueDate(), r.getAmount(),
                    r.getDiscount() != null ? r.getDiscount() : BigDecimal.ZERO));
        }
        List<AdmissionPackageSplitter.CourseShare> shares = AdmissionPackageSplitter.split(fees, rows, paid);

        String reason = pkg.getDiscount() != null && StringUtils.hasText(pkg.getDiscount().getReason())
                ? "Package discount: " + pkg.getDiscount().getReason().trim() : "Package discount";
        List<String> packageSessionIds = new ArrayList<>();
        List<AdmissionPackagePreviewDTO.Course> previewCourses = new ArrayList<>();
        for (int i = 0; i < assignments.size(); i++) {
            AssignmentItemDTO a = assignments.get(i);
            AdmissionPackageSplitter.CourseShare share = shares.get(i);
            packageSessionIds.add(a.getPackageSessionId());

            List<InstallmentScheduleDTO.RowDTO> courseRows = new ArrayList<>();
            List<AdmissionPackagePreviewDTO.Row> previewRows = new ArrayList<>();
            for (AdmissionPackageSplitter.CourseRow cr : share.rows()) {
                courseRows.add(InstallmentScheduleDTO.RowDTO.builder()
                        .dueDate(cr.dueDate()).amount(cr.amount()).discount(cr.discount()).build());
                previewRows.add(AdmissionPackagePreviewDTO.Row.builder()
                        .dueDate(cr.dueDate()).amount(cr.amount()).discount(cr.discount()).build());
            }
            boolean pays = share.paidAtAdmission().signum() > 0;
            a.setCpoConfig(CpoEnrollmentConfigDTO.builder()
                    .installmentSchedule(InstallmentScheduleDTO.builder().rows(courseRows).build())
                    // The rows carry the discount amounts; this only names it on the course's record.
                    .cpoDiscount(share.discount().signum() > 0
                            ? DiscountSpecDTO.builder().type(DiscountSpecDTO.TYPE_FLAT)
                                    .value(share.discount().doubleValue()).reason(reason).build()
                            : null)
                    .paymentMode(pays ? "OFFLINE" : "SKIP")
                    .paymentAmount(pays ? share.paidAtAdmission().doubleValue() : null)
                    .paymentReference(pkg.getPaymentReference())
                    .paymentDetails(pkg.getPaymentDetails())
                    .build());

            previewCourses.add(AdmissionPackagePreviewDTO.Course.builder()
                    .packageSessionId(a.getPackageSessionId())
                    .fee(share.fee()).discount(share.discount()).net(share.net())
                    .paidAtAdmission(share.paidAtAdmission())
                    .rows(previewRows)
                    .build());
        }

        BigDecimal feeTotal = shares.stream().map(AdmissionPackageSplitter.CourseShare::fee).reduce(BigDecimal.ZERO, BigDecimal::add);
        BigDecimal discountTotal = shares.stream().map(AdmissionPackageSplitter.CourseShare::discount).reduce(BigDecimal.ZERO, BigDecimal::add);
        AdmissionPackagePreviewDTO preview = AdmissionPackagePreviewDTO.builder()
                .feeTotal(feeTotal).discountTotal(discountTotal).netTotal(feeTotal.subtract(discountTotal))
                .paidAtAdmission(paid.setScale(2, java.math.RoundingMode.HALF_UP))
                .courses(previewCourses)
                .admissionPackageIds(new ArrayList<>())
                .build();
        return new Plan(pkg, packageSessionIds, shares, preview);
    }

    /**
     * Records one learner's package once their courses are enrolled.
     *
     * @param userPlanIdBySession the learner's new plan per course; courses that did not enroll
     *                            are absent and left out of the package
     * @return the package id, or null when none of the courses enrolled
     */
    @Transactional
    public String save(Plan plan, String instituteId, String userId, Map<String, String> userPlanIdBySession,
                       String adminUserId) {
        if (userPlanIdBySession == null || userPlanIdBySession.isEmpty()) return null;
        AdmissionPackage pkg = new AdmissionPackage();
        pkg.setInstituteId(instituteId);
        pkg.setUserId(userId);
        pkg.setFeeTotal(plan.preview().getFeeTotal());
        pkg.setDiscountTotal(plan.preview().getDiscountTotal());
        pkg.setNetTotal(plan.preview().getNetTotal());
        if (plan.request().getDiscount() != null) pkg.setDiscountReason(plan.request().getDiscount().getReason());
        try {
            pkg.setScheduleJson(MAPPER.writeValueAsString(plan.request().getRows()));
        } catch (Exception e) {
            log.warn("Could not serialise admission package schedule: {}", e.getMessage());
        }
        pkg.setCreatedByUserId(adminUserId);
        pkg = admissionPackageRepository.save(pkg);

        for (int i = 0; i < plan.packageSessionIds().size(); i++) {
            String session = plan.packageSessionIds().get(i);
            String userPlanId = userPlanIdBySession.get(session);
            if (userPlanId == null) continue;
            AdmissionPackageSplitter.CourseShare share = plan.shares().get(i);
            AdmissionPackageCourse course = new AdmissionPackageCourse();
            course.setAdmissionPackageId(pkg.getId());
            course.setUserPlanId(userPlanId);
            course.setPackageSessionId(session);
            course.setPosition(i);
            course.setFee(share.fee());
            course.setDiscount(share.discount());
            admissionPackageCourseRepository.save(course);
        }
        log.info("Admission package {} saved for user {} with {} course(s)", pkg.getId(), userId,
                userPlanIdBySession.size());
        return pkg.getId();
    }

    private BigDecimal courseFee(DefaultInviteResolver.ResolvedConfig config) {
        String type = config.getPaymentOption() != null ? config.getPaymentOption().getType() : null;
        String label = config.getPackageSession() != null && config.getPackageSession().getPackageEntity() != null
                ? config.getPackageSession().getPackageEntity().getPackageName()
                : config.getPaymentPlan() != null ? config.getPaymentPlan().getName() : null;
        String name = StringUtils.hasText(label) ? label : "A course";
        if (PaymentOptionType.CPO.name().equalsIgnoreCase(type)) {
            String cpoId = config.getPaymentOption().getComplexPaymentOptionId();
            if (!StringUtils.hasText(cpoId)) {
                throw new VacademyException(name + " has no fee plan behind its payment option");
            }
            return installmentScheduleService.packageFee(cpoId, name);
        }
        if (PaymentOptionType.ONE_TIME.name().equalsIgnoreCase(type)) {
            double price = config.getPaymentPlan() != null ? config.getPaymentPlan().getActualPrice() : 0d;
            if (price <= 0) {
                throw new VacademyException(name + " is free, so it cannot be part of a paid package");
            }
            return BigDecimal.valueOf(price).setScale(2, java.math.RoundingMode.HALF_UP);
        }
        throw new VacademyException(name + " uses a " + (type != null ? type.toLowerCase() : "free")
                + " payment option; only one-time prices and installment plans can be part of a package");
    }
}
