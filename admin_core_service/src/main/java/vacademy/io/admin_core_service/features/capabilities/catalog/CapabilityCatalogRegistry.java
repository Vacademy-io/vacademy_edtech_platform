package vacademy.io.admin_core_service.features.capabilities.catalog;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.extern.slf4j.Slf4j;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * Loads {@code capabilities/catalog.json} at startup, validates it and serves it (spec §4,
 * §12.1). An invalid catalogue FAILS BOOT: module and feature keys are stored in
 * {@code institute_module_entitlement}, so a typo or a duplicate would silently switch
 * features off for MANAGED institutes.
 *
 * <p>Also serves {@code capabilities/nav-manifest.json} when present (generated by the admin
 * app's vitest; null when absent). The manifest is passed through as-is, unvalidated.
 */
@Slf4j
@Component
public class CapabilityCatalogRegistry {

    public static final String CATALOG_RESOURCE = "capabilities/catalog.json";
    public static final String NAV_MANIFEST_RESOURCE = "capabilities/nav-manifest.json";

    /** Lower-case key segments; feature keys are {@code <module>.<segment>}. */
    private static final Pattern MODULE_KEY = Pattern.compile("[a-z][a-z0-9_]{0,63}");
    private static final Pattern FEATURE_SUFFIX = Pattern.compile("[a-z][a-z0-9_]{0,63}");
    private static final List<String> GOVERNS_FIELDS =
            List.of("nav", "widgets", "quick_actions", "assistant_groups", "setup_steps", "routes");

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private final CapabilityCatalog catalog;
    private final Map<String, CapabilityCatalog.Module> modulesByKey;
    private final Map<String, CapabilityCatalog.Feature> featuresByKey;
    private final JsonNode navManifest;

    public CapabilityCatalogRegistry() {
        this(readResource(CATALOG_RESOURCE, true), readResource(NAV_MANIFEST_RESOURCE, false));
    }

    /** For tests: build from already-parsed JSON. */
    public CapabilityCatalogRegistry(JsonNode catalogJson, JsonNode navManifest) {
        this.catalog = parse(catalogJson);
        this.modulesByKey = catalog.modulesByKey();
        this.featuresByKey = catalog.featuresByKey();
        this.navManifest = navManifest;
        log.info("Capability catalogue v{} loaded: {} modules, {} features, nav manifest {}",
                catalog.version(), modulesByKey.size(), featuresByKey.size(),
                navManifest == null ? "absent" : "present");
    }

    // ── Accessors ────────────────────────────────────────────────────────────

    public CapabilityCatalog catalog() {
        return catalog;
    }

    public int version() {
        return catalog.version();
    }

    public List<CapabilityCatalog.Module> modules() {
        return catalog.modules();
    }

    public Map<String, CapabilityCatalog.Module> modulesByKey() {
        return modulesByKey;
    }

    public Map<String, CapabilityCatalog.Feature> featuresByKey() {
        return featuresByKey;
    }

    public JsonNode rawCatalog() {
        return catalog.raw();
    }

    /** The generated nav manifest, or null when the file is not on the classpath. */
    public JsonNode navManifest() {
        return navManifest;
    }

    public boolean isModule(String key) {
        return modulesByKey.containsKey(key);
    }

    public boolean isFeature(String key) {
        return featuresByKey.containsKey(key);
    }

    public boolean isKnownKey(String key) {
        return isModule(key) || isFeature(key);
    }

    public boolean isCoreModule(String key) {
        CapabilityCatalog.Module m = modulesByKey.get(key);
        return m != null && m.core();
    }

    // ── Parsing + validation ─────────────────────────────────────────────────

    /**
     * Parses and validates a catalogue. Throws {@link IllegalStateException} listing every
     * problem found (not just the first) so one boot failure shows the whole fix list.
     */
    public static CapabilityCatalog parse(JsonNode root) {
        List<String> errors = new ArrayList<>();
        if (root == null || !root.isObject()) {
            throw new IllegalStateException("Invalid capability catalogue: root must be a JSON object");
        }
        JsonNode versionNode = root.get("version");
        int version = 0;
        if (versionNode == null || !versionNode.canConvertToInt() || !versionNode.isIntegralNumber()
                || versionNode.asInt() < 1) {
            errors.add("version must be an integer >= 1");
        } else {
            version = versionNode.asInt();
        }

        JsonNode modulesNode = root.get("modules");
        List<CapabilityCatalog.Module> modules = new ArrayList<>();
        Set<String> moduleKeys = new HashSet<>();
        Set<String> featureKeys = new HashSet<>();
        boolean anyCore = false;

        if (modulesNode == null || !modulesNode.isArray() || modulesNode.isEmpty()) {
            errors.add("modules must be a non-empty array");
        } else {
            int mi = 0;
            for (JsonNode m : modulesNode) {
                String where = "modules[" + mi++ + "]";
                if (!m.isObject()) {
                    errors.add(where + " must be an object");
                    continue;
                }
                String key = text(m, "key");
                if (key == null || !MODULE_KEY.matcher(key).matches()) {
                    errors.add(where + ".key must match " + MODULE_KEY.pattern() + " (got " + key + ")");
                    continue;
                }
                where = "module '" + key + "'";
                if (!moduleKeys.add(key)) {
                    errors.add("duplicate module key '" + key + "'");
                }
                String label = text(m, "label");
                if (label == null || label.isBlank()) {
                    errors.add(where + ": label is required");
                }
                JsonNode coreNode = m.get("core");
                if (coreNode == null || !coreNode.isBoolean()) {
                    errors.add(where + ": core must be a boolean");
                }
                boolean core = coreNode != null && coreNode.asBoolean(false);
                anyCore |= core;

                List<CapabilityCatalog.Feature> features = new ArrayList<>();
                JsonNode featuresNode = m.get("features");
                if (featuresNode == null || !featuresNode.isArray() || featuresNode.isEmpty()) {
                    errors.add(where + ": features must be a non-empty array");
                } else {
                    int fi = 0;
                    for (JsonNode f : featuresNode) {
                        String fwhere = where + ".features[" + fi++ + "]";
                        CapabilityCatalog.Feature feature = parseFeature(f, key, fwhere, errors);
                        if (feature == null) {
                            continue;
                        }
                        if (!featureKeys.add(feature.key())) {
                            errors.add("duplicate feature key '" + feature.key() + "'");
                        }
                        features.add(feature);
                    }
                }
                modules.add(new CapabilityCatalog.Module(key, label, text(m, "description"), text(m, "rail"),
                        core, Collections.unmodifiableList(features)));
            }
        }
        for (String fk : featureKeys) {
            if (moduleKeys.contains(fk)) {
                errors.add("key '" + fk + "' is both a module and a feature");
            }
        }
        if (modulesNode != null && modulesNode.isArray() && !modulesNode.isEmpty() && !anyCore) {
            errors.add("at least one module must have core: true");
        }
        if (!errors.isEmpty()) {
            throw new IllegalStateException("Invalid capability catalogue (" + errors.size() + " problem(s)): "
                    + String.join("; ", errors));
        }
        return new CapabilityCatalog(version, Collections.unmodifiableList(modules), root);
    }

    private static CapabilityCatalog.Feature parseFeature(JsonNode f, String moduleKey, String where,
                                                         List<String> errors) {
        if (!f.isObject()) {
            errors.add(where + " must be an object");
            return null;
        }
        String key = text(f, "key");
        String prefix = moduleKey + ".";
        if (key == null || !key.startsWith(prefix)
                || !FEATURE_SUFFIX.matcher(key.substring(prefix.length())).matches()) {
            errors.add(where + ".key must be '" + prefix + "<segment>' (got " + key + ")");
            return null;
        }
        String fwhere = "feature '" + key + "'";
        String label = text(f, "label");
        if (label == null || label.isBlank()) {
            errors.add(fwhere + ": label is required");
        }
        JsonNode defaultOn = f.get("default_on");
        if (defaultOn == null || !defaultOn.isBoolean()) {
            errors.add(fwhere + ": default_on must be a boolean");
        }
        JsonNode governsNode = f.get("governs");
        CapabilityCatalog.Governs governs = null;
        if (governsNode == null || !governsNode.isObject()) {
            errors.add(fwhere + ": governs must be an object");
        } else {
            List<List<String>> lists = new ArrayList<>();
            for (String field : GOVERNS_FIELDS) {
                lists.add(stringList(governsNode.get(field), fwhere + ".governs." + field, errors));
            }
            for (String nav : lists.get(0)) {
                String[] parts = nav.split("/", -1);
                if (parts.length > 2 || parts[0].isBlank() || (parts.length == 2 && parts[1].isBlank())) {
                    errors.add(fwhere + ": nav entry '" + nav + "' must be 'tab' or 'tab/sub'");
                }
            }
            governs = new CapabilityCatalog.Governs(lists.get(0), lists.get(1), lists.get(2), lists.get(3),
                    lists.get(4), lists.get(5));
        }
        List<String> settingKeys = stringList(f.get("setting_keys"), fwhere + ".setting_keys", errors);
        return new CapabilityCatalog.Feature(key, moduleKey, label, text(f, "description"),
                defaultOn != null && defaultOn.asBoolean(false), governs, settingKeys);
    }

    private static List<String> stringList(JsonNode node, String where, List<String> errors) {
        if (node == null || !node.isArray()) {
            errors.add(where + " must be an array");
            return List.of();
        }
        List<String> out = new ArrayList<>();
        for (JsonNode item : node) {
            if (!item.isTextual() || item.asText().isBlank()) {
                errors.add(where + " must contain non-blank strings");
            } else {
                out.add(item.asText());
            }
        }
        return Collections.unmodifiableList(out);
    }

    private static String text(JsonNode node, String field) {
        JsonNode v = node.get(field);
        return v == null || v.isNull() ? null : v.asText();
    }

    private static JsonNode readResource(String path, boolean required) {
        ClassPathResource resource = new ClassPathResource(path);
        if (!resource.exists()) {
            if (required) {
                throw new IllegalStateException("Capability catalogue missing from the classpath: " + path);
            }
            return null;
        }
        try (InputStream in = resource.getInputStream()) {
            return MAPPER.readTree(in);
        } catch (IOException e) {
            if (required) {
                throw new IllegalStateException("Capability catalogue is not valid JSON: " + path + ": "
                        + e.getMessage(), e);
            }
            log.error("Ignoring unreadable {}: {}", path, e.getMessage());
            return null;
        }
    }
}
