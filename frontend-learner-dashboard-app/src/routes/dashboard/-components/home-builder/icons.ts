/** The named icon, or a neutral fallback for a name this build does not know. */
export const shortcutIcon = (name: string | null | undefined): Icon =>
  (name && Object.prototype.hasOwnProperty.call(SHORTCUT_ICONS, name) ? SHORTCUT_ICONS[name] : undefined) ?? Star;
